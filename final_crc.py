# Nested loop
fold_num = 0
for train_idx, test_idx in outer_cv.split(X_training_scaled, y_training):
    fold_num += 1

    # Get train/test split for this fold
    X_train_fold = X_training_scaled[train_idx]
    y_train_fold = y_training.iloc[train_idx]
    X_test_fold = X_training_scaled[test_idx]
    y_test_fold = y_training.iloc[test_idx]

    print(f"Outer Fold {fold_num}/5:")

    # ═════════════════════════════════════════════════════════════════════════════
