class ACOFeatureSelector:
    """
    Ant Colony Optimization for Feature Selection
    FULL 30 iterations, NO CV folds (training AUC only - fast!)
    """

    def __init__(self, n_ants=20, n_iterations=30, tau_init=1.0, rho=0.1, q=100):
        """
        Parameters:
        n_ants: number of ants per iteration
        n_iterations: number of iterations (1-30)
        tau_init: initial pheromone level
        rho: evaporation rate
        q: pheromone deposit constant
        """
        self.n_ants = n_ants
        self.n_iterations = n_iterations
        self.tau_init = tau_init
        self.rho = rho
        self.q = q
        self.pheromone = None
        self.best_features = None
        self.best_score = 0
        self.iteration_scores = []

    def fit(self, X, y, clf):
        """
        Run ACO to select features
        X: training features
        y: training labels
        clf: classifier to evaluate features (LogisticRegression)
        """

        n_features = X.shape[1]

        # Initialize pheromone
        self.pheromone = np.full(n_features, self.tau_init)

        print(f"Running ACO: {self.n_ants} ants × {self.n_iterations} iterations")
        print(f"Evaluation: Training AUC ONLY (no CV folds - FAST!)\n")

        best_score = 0
        best_features = None

        # Main ACO loop - FULL 30 iterations
        for iteration in range(1, self.n_iterations + 1):
            ant_scores = []
            ant_solutions = []

            # Each ant constructs a solution
            for ant in range(self.n_ants):
                # Probabilistic feature selection based on current pheromone
                probabilities = self.pheromone / self.pheromone.sum()

                # Select ~40% of features (min 3)
                n_select = max(3, int(n_features * 0.4))
                selected_features = np.random.choice(
                    n_features,
                    size=n_select,
                    replace=False,
                    p=probabilities
                )

                # Evaluate this feature subset
                if len(selected_features) > 0:
                    X_subset = X[:, selected_features]

                    # Train classifier on this feature subset
                    # NO CV folds - just train on full training data (FAST!)
                    clf_copy = LogisticRegression(C=0.1, max_iter=2000, random_state=42)
                    clf_copy.fit(X_subset, y)

                    # Get predictions on same data
                    y_pred_proba = clf_copy.predict_proba(X_subset)[:, 1]

                    # Calculate AUC
                    try:
                        score = roc_auc_score(y, y_pred_proba)
                    except:
                        score = 0

                    ant_solutions.append(selected_features)
                    ant_scores.append(score)

                    # Track overall best
                    if score > best_score:
                        best_score = score
                        best_features = selected_features.copy()

            # Pheromone evaporation (global)
            self.pheromone *= (1 - self.rho)

            # Pheromone deposit (local - on good solutions)
            for features, score in zip(ant_solutions, ant_scores):
                pheromone_deposit = self.q * score
                for feat_idx in features:
                    self.pheromone[feat_idx] += pheromone_deposit

            # Store best score for this iteration
            self.iteration_scores.append(best_score)

            # Print progress
            print(f"  Iteration {iteration:2d}/30: Best AUC = {best_score:.4f}")

        self.best_features = best_features
        self.best_score = best_score

        return best_features, best_score, self.iteration_scores

